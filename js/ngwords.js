const MIN = 1, MAX = 12;

function h32(s) {
  let x = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    x ^= s.charCodeAt(i);
    x = Math.imul(x, 0x01000193) >>> 0;
  }
  return x;
}

export function ngNormalize(s) {
  return String(s)
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\u30A1-\u30F6]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/[\s\u3000・、。．.,\-_~〜ー*＊☆★♪♡\u2665!！?？'"「」『』()（）[\]｛｝{}]/g, "");
}

export function hasNgWord(name) {
  const n = ngNormalize(name);
  for (let i = 0; i < n.length; i++) {
    for (let len = MIN; len <= MAX && i + len <= n.length; len++) {
      if (NG.has(h32(n.slice(i, i + len)))) return true;
    }
  }
  return false;
}
